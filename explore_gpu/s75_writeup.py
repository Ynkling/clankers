#!/usr/bin/env python
"""
explore_gpu/s75_writeup.py — the descriptions that explore_out/I/gpu/s75_S4_prerun_note_2026-10-12.md promised for S75 at
S = 4, generated from the records. EXPLORATORY; nothing here is a reading (the registered result is UNTESTED: VALID
failed). Not imported by explore_gpu/s75_s4.py, so S75's code SHA (5fb120a92d69) does not depend on this file.

    python -m explore_gpu.s75_writeup        -> explore_out/I/gpu/s75_S4_descriptions.md

WHAT IT WRITES (all from explore_out/I/gpu/s75_S4_*_results.json, records under the current code SHA):
  1. the per-run ROUTED trajectory of every learned arm: ROUTED (the registered definition: at every gate layer eta^2 by
     source at word positions >= 0.9 and a one-to-one source -> channel map) at each evaluation, as a string with one
     character per evaluation (R routed, o one-to-one map with eta^2 < 0.9, . neither);
  2. for every WIDE_SPLIT run, every check of the split trigger that was eligible: its step, the probe's SET accuracy and
     the previous check's, the map before, on_target, fired or blocked (and by what), whether the run was ROUTED at
     the evaluation of that step (which precedes the trigger), at the next evaluation, and at the end;
  3. the counts the note fixed: fires on a one-to-one map; runs ROUTED at the evaluation before some fire and not
     ROUTED at the end;
  4. WIDE_SLOW (the no-split twin) beside WIDE_SPLIT, paired by seed: ROUTED, eta^2, SET and splits; "pending" for a
     seed whose WIDE_SLOW record has not landed.
"""

import json
import os
import statistics
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

from explore_gpu import s75_s4 as s75

LEARNED = ("WIDE_SPLIT", "REG3", "WIDE_SLOW")


def routed_at(e):
    """The registered ROUTED criterion applied to one evaluation (explore_i_dense.routed applies it to the end)."""
    rt = (e or {}).get("routing") or {}
    return bool(rt) and all(v["eta"] >= 0.9 and v["one_to_one"] for v in rt.values())


def mark(e):
    rt = (e or {}).get("routing") or {}
    if not rt:
        return "?"
    if routed_at(e):
        return "R"
    return "o" if all(v["one_to_one"] for v in rt.values()) else "."


def eta_str(e):
    rt = (e or {}).get("routing") or {}
    return "/".join(f"{v['eta']:.2f}" for v in rt.values()) or "-"


def at_step(rec, step):
    for e in rec.get("curve") or []:
        if e["step"] == step:
            return e
    return None


def one_to_one(cmap, S):
    return cmap is not None and len(set(cmap)) == S


def main(out_path=None):
    st = s75.load_all()
    sha = s75.code_sha()[0]
    S = s75.CONFIG["S"]
    R = {a: s75.runs_of(st, a, sha) for a in s75.arms(True)}
    hws = sorted({r.get("hw") for rr in R.values() for r in rr.values() if r.get("hw")})
    L = [f"# S75 at S = 4: descriptions promised by the pre-run note (EXPLORATORY)", "",
         f"Generated by `python -m explore_gpu.s75_writeup` from the records under code SHA {sha} ({', '.join(hws) or 'no'} "
         f"records). The registered result is **UNTESTED** (VALID failed: ORACLE did not reach 0.9 on both seeds). "
         f"Nothing below is a reading: no 'carries' or 'does not carry' applies, whatever the counts.", ""]

    # 1. ROUTED trajectories
    L += ["## 1. ROUTED at each evaluation (every 1200 updates)", "",
          "R = ROUTED (eta^2 >= 0.9 and a one-to-one map at every gate layer); o = one-to-one map, eta^2 < 0.9 at some "
          "layer; . = not one-to-one. Last column: ROUTED at the end (the registered outcome).", ""]
    for a in LEARNED:
        rr = R.get(a, {})
        if not rr:
            L.append(f"- {a}: no records yet")
            continue
        L.append(f"**{a}** ({sum(routed_at(r['end']) for r in rr.values())}/{len(rr)} ROUTED at the end)")
        L.append("")
        L.append("    seed  trajectory               end  eta^2 at the end (per gate layer)")
        for sd, r in sorted(rr.items()):
            traj = "".join(mark(e) for e in r.get("curve") or [])
            L.append(f"    {sd}   {traj:<24} {'R' if routed_at(r['end']) else '-':<4} {eta_str(r['end'])}")
        L.append("")

    # 2-3. split checks of WIDE_SPLIT
    L += ["## 2. WIDE_SPLIT: every eligible check of the split trigger", "",
          "Trigger: checks every 2400 updates from 4800; eligible when the 64-sequence probe's SET < 0.88 and the rise "
          "since the previous check < 0.02; at most 3 fires, at least 4800 apart (explore_i_common.make_split). "
          "'routed@step' is the evaluation at the same step, which runs before the trigger; 'routed@next' the one 1200 "
          "updates later.", "",
          "| seed | step | probe SET (prev) | map before | one-to-one | on_target | fired | routed@step | routed@next | routed@end |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    fires_121 = fires = 0
    undone = []
    rr = R.get("WIDE_SPLIT", {})
    for sd, r in sorted(rr.items()):
        rows = [c for c in (r.get("checks") or []) if c.get("eligible")]
        routed_before_fire = False
        for c in rows:
            e0, e1 = at_step(r, c["step"]), at_step(r, c["step"] + 1200)
            status = "fired" if c.get("fired") else f"blocked ({c.get('blocked_by', '?')})"
            oto = one_to_one(c.get("map_before"), S)
            prev = "-" if c.get("prev") is None else f"{c['prev']:.3f}"
            L.append(f"| {sd} | {c['step']} | {c['acc']:.3f} ({prev}) | "
                     f"{c.get('map_before')} | {'yes' if oto else 'no'} | {c.get('on_target')} | {status} | "
                     f"{'R' if routed_at(e0) else '-'} | {'R' if routed_at(e1) else '-'} | {'R' if routed_at(r['end']) else '-'} |")
            if c.get("fired"):
                fires += 1
                fires_121 += oto
                routed_before_fire |= routed_at(e0)
        if routed_before_fire and not routed_at(r["end"]):
            undone.append(sd)
        if not rows:
            L.append(f"| {sd} | – | no eligible check | | | | | | | {'R' if routed_at(r['end']) else '-'} |")
    L += ["", "## 3. The counts the note fixed", "",
          f"- fires: {fires} over {len(rr)} WIDE_SPLIT runs; fires on a one-to-one map: {fires_121}",
          f"- runs ROUTED at the evaluation before a fire and not ROUTED at the end: {len(undone)} {undone}",
          f"- runs with at least one fire: {sum(any(c.get('fired') for c in (r.get('checks') or [])) for r in rr.values())}"
          f"/{len(rr)}", ""]

    # 4. WIDE_SLOW paired by seed
    slow = R.get("WIDE_SLOW", {})
    L += ["## 4. WIDE_SPLIT beside WIDE_SLOW (its no-split twin), paired by seed", "",
          "| seed | WIDE_SPLIT routed@end | fires | eta^2 | SET | WIDE_SLOW routed@end | eta^2 | SET |",
          "|---|---|---|---|---|---|---|---|"]
    both = [0, 0, 0, 0]                                       # (split R, slow R), (R, -), (-, R), (-, -)
    for sd in s75.SEEDS:
        a, b = rr.get(sd), slow.get(sd)
        if a is None and b is None:
            continue
        def cols(r, pending):
            if r is None:
                return [pending, "-", "-"]
            return ["R" if routed_at(r["end"]) else "-", eta_str(r["end"]), f"{r['end']['set']:.3f}"]
        fa = "-" if a is None else str(sum(bool(c.get("fired")) for c in (a.get("checks") or [])))
        ca, cb = cols(a, "missing"), cols(b, "pending")
        L.append("| " + " | ".join([str(sd), ca[0], fa, ca[1], ca[2]] + cb) + " |")
        if a and b:
            both[(0 if routed_at(a["end"]) else 2) + (0 if routed_at(b["end"]) else 1)] += 1
    n_pair = sum(both)
    L += ["", f"Paired seeds with both records: {n_pair}. ROUTED in both {both[0]}, WIDE_SPLIT only {both[1]}, "
          f"WIDE_SLOW only {both[2]}, neither {both[3]}." + ("" if n_pair == len(s75.SEEDS) else
          f" WIDE_SLOW records are pending for {len(s75.SEEDS) - len(slow)} of {len(s75.SEEDS)} seeds; this section is "
          f"regenerated when they land."), ""]

    txt = "\n".join(L) + "\n"
    out_path = out_path or os.path.join(s75.OUT, "s75_S4_descriptions.md")
    with open(out_path, "w") as f:
        f.write(txt)
    print(txt)
    return txt


if __name__ == "__main__":
    main()
