#!/usr/bin/env python
"""
explore_gpu/window_gate_writeup.py — the descriptions fixed in explore_out/I/gpu/mainline/window_gate_prerun_note_2026-10-12.md
for the GPU run of test_window_gate's Part C / D arms (explore_gpu.mainline, seeds 2540-2559). EXPLORATORY; no reading.

    python -m explore_gpu.window_gate_writeup      -> explore_out/I/gpu/mainline/window_gate_descriptions.md

Everything is computed with test_window_gate's own functions (tally: its validity rule, success = BOUND ROUTED, the
seed pairing; tsr.wilson), on four sets of records, side by side and never pooled across the GPU and the CPUs:
  GPU      explore_out/I/gpu/mainline/test_window_gate_NVIDIA_GeForce_GTX_1660_SUPER_results.json, the planned seeds
           only (the RTX 3070's aborted attempt, if any of its records exist, is not described)
  X, L     results/X/window_gate_results.json, results/L/window_gate_results.json (the test's own machines, their seeds)
  pooled   X and L summed, as the test pools its primary claims (b and c summed over both machines' pairs)
Printed per set: Part C's validity by the test's rule (CEIL_C binds on both of its 2 seeds); each arm's BOUND ROUTED count
with its Wilson 95% interval; and, paired by seed, the discordant pairs of WIN3_SPLIT_D8 against each control (HINGE_D8:
the test's G2 pairing; WIN3_SLOW_D8: G4) and of WIN3_SLOW_D8 against HINGE_D8 (the test's printed "original G2"):
b = first arm only, c = control only. No p-value, no SHOWN / NOT SHOWN, no reading.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import test_window_gate as twg
import test_stream_recipe as tsr

ARMS = ("WIN3_SPLIT_D8", "HINGE_D8", "WIN3_SLOW_D8")
PAIRS = (("WIN3_SPLIT_D8", "HINGE_D8", "G2's pairing"), ("WIN3_SPLIT_D8", "WIN3_SLOW_D8", "G4's pairing"),
         ("WIN3_SLOW_D8", "HINGE_D8", "the test's printed 'original G2'"))
GPU_SEEDS = dict(CEIL_C=(2540, 2541), **{a: tuple(range(2540, 2560)) for a in ARMS})
GPU_DIR = os.path.join(HERE, "explore_out", "I", "gpu", "mainline")
GPU_FILE = "test_window_gate_NVIDIA_GeForce_GTX_1660_SUPER_results.json"


def describe(store, seeds):
    t = twg.tally(store, seeds)
    n_c, valid = t["valid"]["C"]
    arms = {}
    for k in ARMS:
        rr = t["rA"][k]
        c = sum(twg.success(k, r) for r in rr.values())
        arms[k] = dict(c=c, n=len(seeds.get(k, ())), have=len(rr))
    pairs = {}
    for a, b, _ in PAIRS:
        d = twg.paired_by(t["rA"][a], t["rA"][b], seeds[a], lambda r, k=a: twg.success(k, r))
        pairs[(a, b)] = dict(n=d["n"], b=d["b"], c=d["c"])
    return dict(valid=valid, ceil_bound=n_c, ceil_n=len(seeds.get("CEIL_C", ())), arms=arms, pairs=pairs)


def load(path):
    with open(path) as f:
        return json.load(f)


def main(out_path=None):
    sets = {}
    gpu_files = [p for p in [os.path.join(GPU_DIR, GPU_FILE)] if os.path.exists(p)]
    for p in gpu_files:
        st = load(p)
        label = st["meta"].get("machine") or ("GPU " + os.path.basename(p))     # "GPU:<model>"
        # the planned seeds, as the test's tally takes them: a missing record shows as "(k missing)" in the BOUND ROUTED
        # table and never shrinks its n (the pairs' n, as in the test, counts seeds with both records ok)
        sets[label] = (st, dict(GPU_SEEDS), sorted({r.get("code_sha") for r in st["runs"].values()} - {None}))
    for m in ("X", "L"):
        st = load(os.path.join(HERE, "results", m, "window_gate_results.json"))
        seeds = {k: tuple(v) for k, v in st["meta"]["seeds"].items()}
        # the test keeps the first start's commit in meta.git and each later start (commit, time, arms added) in
        # meta.starts: both are listed
        code = [f"{st['meta'].get('git')} (first start {st['meta'].get('started')})"] + [
            f"{x.get('git')} (start {x.get('started')}; arms added {', '.join(x.get('arms_added') or []) or '-'})"
            for x in st["meta"].get("starts") or []]
        sets[m] = (st, seeds, code)
    D = {name: describe(st, seeds) for name, (st, seeds, _) in sets.items()}
    if "X" in D and "L" in D:                              # the test's pooling: counts and pairs summed over X and L
        x, l_ = D["X"], D["L"]
        D["pooled X+L"] = dict(valid=x["valid"] and l_["valid"], ceil_bound=x["ceil_bound"] + l_["ceil_bound"],
                               ceil_n=x["ceil_n"] + l_["ceil_n"],
                               arms={k: {f: x["arms"][k][f] + l_["arms"][k][f] for f in ("c", "n", "have")} for k in ARMS},
                               pairs={pk: {f: x["pairs"][pk][f] + l_["pairs"][pk][f] for f in ("n", "b", "c")} for pk in x["pairs"]})
    L = ["# test_window_gate Part C / D on a GPU, beside X, L and the pooled counts (EXPLORATORY; no reading)", "",
         "Generated by `python -m explore_gpu.window_gate_writeup` (the pre-run note fixes what is described). The GPU run "
         "is a new run of these arms on new seeds (2540-2559) through explore_gpu.mainline; it is never pooled with X or L.", ""]
    for name, (st, seeds, shas) in sets.items():
        plan = {f"{k}|{s}" for k, v in seeds.items() for s in v}
        have = [k for k in plan if k in st["runs"]]
        ok = sum(bool((st["runs"][k] or {}).get("ok")) for k in have)
        extra = len(set(st["runs"]) - plan)
        L.append(f"- {name}: {len(have)}/{len(plan)} planned records present, {ok} ok; {extra} records outside the plan; "
                 f"code: {'; '.join(map(str, shas)) or '-'}")
    L += ["", "## Validity (the test's rule: CEIL_C binds on both of its 2 seeds; Part C and D are UNTESTED otherwise)", "",
          "| set | CEIL_C bound | Part C |", "|---|---|---|"]
    for name, d in D.items():
        L.append(f"| {name} | {d['ceil_bound']}/{d['ceil_n']} | {'VALID' if d['valid'] else 'NOT VALID'} |")
    L += ["", "## BOUND ROUTED per arm (Wilson 95%)", "",
          "| arm | " + " | ".join(D) + " |", "|---|" + "---|" * len(D)]
    for k in ARMS:
        cells = []
        for d in D.values():
            a = d["arms"][k]
            lo, hi = tsr.wilson(a["c"], a["n"]) if a["n"] else (0.0, 1.0)
            miss = "" if a["have"] == a["n"] else f" ({a['n'] - a['have']} missing)"
            cells.append(f"{a['c']}/{a['n']} [{lo:.2f}, {hi:.2f}]{miss}")
        L.append(f"| {k} | " + " | ".join(cells) + " |")
    L += ["", "## Discordant pairs against the controls, paired by seed (b = first arm only, c = control only)", "",
          "| pairing | " + " | ".join(D) + " |", "|---|" + "---|" * len(D)]
    for a, b, what in PAIRS:
        L.append(f"| {a} vs {b} ({what}) | " + " | ".join(f"b {d['pairs'][(a, b)]['b']}, c {d['pairs'][(a, b)]['c']} "
                                                          f"(n {d['pairs'][(a, b)]['n']})" for d in D.values()) + " |")
    L += ["", "No p-value and no SHOWN / NOT SHOWN label are printed for the GPU run (the pre-run note: no reading).", ""]
    txt = "\n".join(L) + "\n"
    out_path = out_path or os.path.join(GPU_DIR, "window_gate_descriptions.md")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as f:
        f.write(txt)
    print(txt)
    return D


if __name__ == "__main__":
    main()
